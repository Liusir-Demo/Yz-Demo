async def generate_one(name, text):
    """生成单个 MP3 文件"""
    mp3_path = os.path.join(OUTPUT_DIR, f"{name}.mp3")
    # edge-tts cli
    cmd = f'edge-tts --voice "{VOICE}" --text "{text}" --write-media "{mp3_path}"'
    # Use subprocess because edge-tts has a CLI
    proc = await asyncio.create_subprocess_shell(
        cmd,
        stdout=asyncio.subprocess.PIPE,
        stderr=asyncio.subprocess.PIPE,
    )
    stdout, stderr = await proc.communicate()
    if proc.returncode == 0:
        print(f"  ✓ {name}.mp3")
        return mp3_path
    else:
        print(f"  ✗ {name} failed: {stderr.decode()}")
        return None


async def main():
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    for name in NARRATIONS:
        print(f"生成: {name}")
        text = NARRATIONS[name].replace("\n", " ").replace('"', "'")
        await generate_one(name, text)


if __name__ == "__main__":
    asyncio.run(main())
